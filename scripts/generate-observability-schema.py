#!/usr/bin/env python3
"""Generate Dart's embedded schema from the one packaged JSON contract."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'linux/ro-installer-observability.json').read_text())
# Packaged Python and embedded Dart must accept the same operation catalogue.
# Report span IDs have their own fixed compatibility contract.
for name in ('payload', 'event'):
    if data['objects'][name]['operationId'] != ['enum', data['operations']]:
        raise SystemExit(f'Operation catalogue differs from {name} schema')
path = ROOT / 'lib/services/observability_schema.g.dart'
source = ("// Generated by scripts/generate-observability-schema.py; do not edit.\n"
          "import 'dart:convert';\n\n"
          "final Map<String, dynamic> observabilitySchema =\n"
          "    jsonDecode(_schemaJson) as Map<String, dynamic>;\n"
          "const _schemaJson = r'''\n" + json.dumps(data, indent=2) + "\n''';\n")
if '--check' in sys.argv:
    if path.read_text() != source:
        raise SystemExit('Generated observability schema is stale')
else:
    path.write_text(source)
